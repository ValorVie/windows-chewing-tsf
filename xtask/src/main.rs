use scoped_error::{Error, expect_error};

mod download;
mod installer;
mod payload;
mod version;
mod zip;

mod flags {
    use super::installer::Target;
    use std::path::PathBuf;

    xflags::xflags! {
        src "src/main.rs"

        /// cargo-xtask helper
        cmd xtask {
            /// Update the version.rc file.
            cmd update-version {
                /// The major version of the release. (u32)
                required --major MAJOR: u32
                /// The minor version of the release. (u32)
                required --minor MINOR: u32
                /// The patch version of the release. (u32)
                required --patch PATCH: u32
                /// Optional build number (u32)
                optional -b, --build BUILD_NUMBER: u32
            }
            /// Build the installer.
            cmd build-installer {
                /// Target platform [gnu, msvc]
                optional -t, --target TARGET: Target
                /// Build release artifact
                optional --release
                /// Build nightly artifact
                optional --nightly
                /// Build the x64 fork variant without ARM64 DLLs.
                optional --without-arm64
            }
            /// Download prebuilt components and verify the signatures.
            cmd download-components {

            }
            /// Build the MSI package
            cmd package-installer {
                /// Package the x64 fork variant without ARM64 DLLs.
                optional --without-arm64
            }
            /// Verify and copy immutable D512 and ORT assets beside the host.
            cmd stage-d512 {
                required --from DIRECTORY: PathBuf
            }
            /// Verify and copy the selected preferences artifact.
            cmd stage-preferences {
                required --from EXECUTABLE: PathBuf
                required --sha256 SHA256: String
            }
            /// Check every active MSI source plus D512 hashes and placement.
            cmd check-installer {
                optional --without-arm64
            }
        }
    }
    // generated start
    // The following code is generated by `xflags` macro.
    // Run `env UPDATE_XFLAGS=1 cargo build` to regenerate.
    #[derive(Debug)]
    pub struct Xtask {
        pub subcommand: XtaskCmd,
    }

    #[derive(Debug)]
    pub enum XtaskCmd {
        UpdateVersion(UpdateVersion),
        BuildInstaller(BuildInstaller),
        DownloadComponents(DownloadComponents),
        PackageInstaller(PackageInstaller),
        StageD512(StageD512),
        StagePreferences(StagePreferences),
        CheckInstaller(CheckInstaller),
    }

    #[derive(Debug)]
    pub struct UpdateVersion {
        pub major: u32,
        pub minor: u32,
        pub patch: u32,
        pub build: Option<u32>,
    }

    #[derive(Debug)]
    pub struct BuildInstaller {
        pub target: Option<Target>,
        pub release: bool,
        pub nightly: bool,
        pub without_arm64: bool,
    }

    #[derive(Debug)]
    pub struct DownloadComponents;

    #[derive(Debug)]
    pub struct PackageInstaller {
        pub without_arm64: bool,
    }

    #[derive(Debug)]
    pub struct StageD512 {
        pub from: PathBuf,
    }

    #[derive(Debug)]
    pub struct StagePreferences {
        pub from: PathBuf,
        pub sha256: String,
    }

    #[derive(Debug)]
    pub struct CheckInstaller {
        pub without_arm64: bool,
    }

    impl Xtask {
        #[allow(dead_code)]
        pub fn from_env_or_exit() -> Self {
            Self::from_env_or_exit_()
        }

        #[allow(dead_code)]
        pub fn from_env() -> xflags::Result<Self> {
            Self::from_env_()
        }

        #[allow(dead_code)]
        pub fn from_vec(args: Vec<std::ffi::OsString>) -> xflags::Result<Self> {
            Self::from_vec_(args)
        }
    }
    // generated end
}

fn main() -> Result<(), Error> {
    expect_error("failed to run command", || {
        let flags = flags::Xtask::from_env()?;

        match flags.subcommand {
            flags::XtaskCmd::UpdateVersion(flags) => {
                version::update_version(flags)?;
            }
            flags::XtaskCmd::BuildInstaller(flags) => {
                installer::build_installer(flags)?;
            }
            flags::XtaskCmd::DownloadComponents(flags) => {
                download::download_components(flags)?;
            }
            flags::XtaskCmd::PackageInstaller(flags) => {
                installer::package_installer(flags)?;
            }
            flags::XtaskCmd::StageD512(flags) => payload::stage_d512(&flags.from)?,
            flags::XtaskCmd::StagePreferences(flags) => {
                payload::stage_preference_artifact(&flags.from, &flags.sha256)?
            }
            flags::XtaskCmd::CheckInstaller(flags) => {
                payload::check_installer(flags.without_arm64)?
            }
        }

        Ok(())
    })
}
